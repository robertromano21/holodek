'use strict';
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const modules = ['scenerySprites', 'scenerySpritesMore', 'sceneryPieces', 'sceneryAssemblies', 'sceneryLayout', 'sceneryGrammar'];
const target = path.join(root, 'assets', 'sceneryGrammar.browser.js');
let source = `// Generated by tools/build-scenery-browser.cjs. Do not edit this file directly.\n(function(root) {\n  'use strict';\n  const factories = Object.create(null);\n  const cache = Object.create(null);\n  function load(id) {\n    if (cache[id]) return cache[id].exports;\n    if (!factories[id]) throw Error('Unknown scenery module: ' + id);\n    const module = { exports: {} };\n    cache[id] = module;\n    factories[id](load, module, module.exports);\n    return module.exports;\n  }\n`;
for (const name of modules) {
  const id = './' + name;
  const body = fs.readFileSync(path.join(root, 'assets', name + '.js'), 'utf8');
  source += `  factories[${JSON.stringify(id)}] = function(require, module, exports) {\n${body}\n  };\n`;
}
source += `  root.SceneryGrammar = load('./sceneryGrammar');\n})(typeof window === 'object' ? window : globalThis);\n`;
fs.writeFileSync(target, source);
console.log(`Built ${path.relative(root, target)} from ${modules.length} scenery modules.`);
